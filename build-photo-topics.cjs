const readingPhotoTopics = {};
for (const l of readings) {
  if (explicitReadingTopics[l.id]) {
    readingPhotoTopics[l.id] = explicitReadingTopics[l.id];
    continue;
  }
  const src0 = l.sources?.[0]?.[0] || '';
  const afterDot = src0.includes('·') ? src0.split('·')[1].trim() : src0.trim();
  const cleanSrc = afterDot
    .replace(/\b(history|overview|timeline|archive|guide|questions|facts|story|exhibition|collection|primary excerpt|original report)\b/gi, '')
    .replace(/\s+/g, ' ')
    .trim();
  readingPhotoTopics[l.id] = cleanSrc.length >= 4 ? cleanSrc : l.englishTitle;
}

